def write_xc() -> None:
    """Pointwise Slater exchange + VWN5 correlation straight out of libxc."""
    rho = np.concatenate(
        [
            np.logspace(-10, 3, 40),  # spans the whole range a molecular grid sees
            np.array([1e-14, 0.5, 1.0, 2.0]),
        ]
    )
    rho = np.sort(rho)
    exc, vxc = dft.libxc.eval_xc("lda,vwn5", rho, spin=0)[:2]
    # libxc screens densities below ~1e-15 to exactly zero; the engine applies
    # its own cutoff there, so those points say nothing about the functional.
    unpolarized = [
        {"rho": float(r), "exc": float(e), "vrho": float(v)}
        for r, e, v in zip(rho, exc, vxc[0])
        if e != 0.0
    ]

    # Spin-polarised values matter from P4 onwards (UKS); pinning them down now
    # keeps the functional a solved problem when that phase starts.
    pairs = [
        (a, b)
        for a in np.logspace(-8, 1, 10)
        for b in (0.0, 1e-8, 1e-3, 0.1, 1.0)
    ]
    ra = np.array([p[0] for p in pairs])
    rb = np.array([p[1] for p in pairs])
    exc_p, vxc_p = dft.libxc.eval_xc("lda,vwn5", (ra, rb), spin=1)[:2]
    polarized = [
        {
            "rho_a": float(a),
            "rho_b": float(b),
            "exc": float(e),
            "vrho_a": float(va),
            "vrho_b": float(vb),
        }
        for a, b, e, va, vb in zip(ra, rb, exc_p, vxc_p[0][:, 0], vxc_p[0][:, 1])
        if e != 0.0
    ]

    dump(
        "xc_lda.json",
        {
            "functional": "LDA exchange (Slater) + VWN5 correlation",
            "source": "libxc via pyscf.dft.libxc.eval_xc('lda,vwn5')",
            "unpolarized": unpolarized,
            "polarized": polarized,
        },
    )


