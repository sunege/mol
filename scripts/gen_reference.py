def make_mol(atoms, unit: str, basis: str, cart: bool, spin: int):
    """One neutral PySCF molecule, refusing a basis the engine would build differently.

    The engine builds every shell from Cartesian functions. For s and p shells
    that is the same thing as PySCF's default spherical ones, which is why the
    STO-3G references use `cart=False`; but a d shell has six Cartesian
    functions and five spherical ones, so a 6-31G* reference made without
    `cart=True` would be for a different basis (benzene: 102 functions
    against 96).
    """
    mol = gto.Mole()
    mol.atom = atoms
    mol.basis = basis
    mol.unit = unit
    mol.cart = cart
    mol.spin = spin
    mol.charge = 0
    mol.verbose = 0
    mol.build()
    assert cart or all(mol.bas_angular(i) < 2 for i in range(mol.nbas)), (
        f"{basis} has d shells and the engine's are Cartesian: pass cart=True"
    )
    return mol


def build_mol(name: str, basis: str = "sto-3g", cart: bool = False, spin: int = 0):
    atoms = [(sym, pos) for sym, pos in GEOMETRIES[name]]
    return make_mol(atoms, "Angstrom", basis, cart, spin)


def engine_normalisation(mol):
    """Factors taking PySCF's AO functions to the engine's.

    libcint normalises a Cartesian shell as a whole, so with `cart=True` the d
    functions do not have unit self-overlap (<xx|xx> = 3 <xy|xy>). The engine
    normalises every Cartesian function individually: engine function i is
    PySCF's times `scale[i]`. For s and p the factors are 1 to rounding.
    """
    return 1.0 / np.sqrt(np.diag(mol.intor("int1e_ovlp")))


def shell_defs(mol) -> list[dict]:
    """The shells in PySCF's own order, so the Rust side can assert it matches."""
    out = []
    for bas_id in range(mol.nbas):
        out.append(
            {
                "center": int(mol.bas_atom(bas_id)),
                "l": int(mol.bas_angular(bas_id)),
                "exponents": [float(x) for x in mol.bas_exp(bas_id)],
                # Published contraction coefficients, not the internally
                # renormalised ones libcint works with.
                "coefficients": [float(c) for c in mol.bas_ctr_coeff(bas_id)[:, 0]],
            }
        )
    return out


def sample_eri(eri, count: int) -> list[dict]:
    """A deterministic sample of (ij|kl) values, so the file stays small."""
    n = eri.shape[0]
    count = min(count, n**4)
    rng = random.Random(SEED)
    seen = set()
    out = []
    while len(out) < count:
        idx = tuple(rng.randrange(n) for _ in range(4))
        if idx in seen:
            continue
        seen.add(idx)
        i, j, k, l = idx
        out.append({"idx": list(idx), "value": float(eri[i, j, k, l])})
    return out


def integral_reference(key: str, name: str, basis: str, cart: bool, full_eri: bool):
    mol = build_mol(name, basis=basis, cart=cart)
    # Matrices over basis functions go into the engine's convention here, so the
    # Rust test compares element for element.
    scale = engine_normalisation(mol)

    def one(name_: str):
        return flat(mol.intor(name_) * scale[:, None] * scale[None, :])

    payload = {
        "molecule": name,
        "basis": basis,
        "cartesian": cart,
        "atoms": [
            {
                "z": int(mol.atom_charge(i)),
                # Bohr: the engine's own units, so the test does no conversion.
                "pos": [float(x) for x in mol.atom_coord(i)],
            }
            for i in range(mol.natm)
        ],
        "shells": shell_defs(mol),
        "ao_labels": [" ".join(lbl.split()) for lbl in mol.ao_labels()],
        "nbf": int(mol.nao),
        "nuclear_repulsion": float(mol.energy_nuc()),
        "normalization": [float(x) for x in scale],
        "overlap": one("int1e_ovlp"),
        "kinetic": one("int1e_kin"),
        "nuclear": one("int1e_nuc"),
    }
    eri = mol.intor("int2e", aosym="s1")
    eri = eri * scale[:, None, None, None] * scale[None, :, None, None]
    eri = eri * scale[None, None, :, None] * scale[None, None, None, :]
    if full_eri:
        payload["eri_full"] = flat(eri)
    payload["eri_samples"] = sample_eri(eri, 300)
    dump(f"integrals_{key}.json", payload)


def scf_reference(
    key: str, name: str, with_density: bool = True, basis: str = "sto-3g", cart: bool = False
):
    mol = build_mol(name, basis=basis, cart=cart)
    mf = dft.RKS(mol)
    mf.xc = "lda,vwn5"
    mf.grids.level = REFERENCE_GRID_LEVEL
    mf.conv_tol = 1e-11
    energy = float(mf.kernel())
    assert mf.converged, f"{name} did not converge"

    dm = mf.make_rdm1()
    if cart:
        # The density's coefficients go the opposite way to a matrix of
        # integrals, so that the energy (a trace of the two) stays the same.
        # Spherical s and p functions are left alone: their factors are 1 to
        # rounding, and applying them would move the STO-3G files by an ulp.
        scale = engine_normalisation(mol)
        dm = dm / scale[:, None] / scale[None, :]
    payload = {
        "molecule": name,
        "basis": basis,
        "functional": "lda,vwn5",
        # Bohr, so the Rust test rebuilds exactly this geometry.
        "atoms": [
            {
                "z": int(mol.atom_charge(i)),
                "pos": [float(x) for x in mol.atom_coord(i)],
            }
            for i in range(mol.natm)
        ],
        "grid_level": REFERENCE_GRID_LEVEL,
        "n_electrons": int(mol.nelectron),
        "nbf": int(mol.nao),
        "nuclear_repulsion": float(mol.energy_nuc()),
        "energy": energy,
        # Per-term breakdown at the converged density, so a Rust failure says
        # which term is wrong instead of only that the total is off.
        "e_core": float(mf.scf_summary["e1"]),
        "e_coulomb": float(mf.scf_summary["coul"]),
        "e_xc": float(mf.scf_summary["exc"]),
        "mo_energies": [float(x) for x in mf.mo_energy],
        "homo": float(mf.mo_energy[mol.nelectron // 2 - 1]),
    }
    if with_density:
        # The Rust test evaluates its energy expression on *this* density matrix,
        # which separates the energy functional from SCF convergence.
        payload["density_matrix"] = flat(dm)
    # How much of the total is quadrature: the coarse-grid number bounds what a
    # Rust grid of modest size can be expected to reproduce.
    coarse = dft.RKS(mol)
    coarse.xc = "lda,vwn5"
    coarse.grids.level = 3
    coarse.conv_tol = 1e-11
    payload["energy_grid_level_3"] = float(coarse.kernel())
    dump(f"scf_{key}.json", payload)


def atomic_reference(filename: str = "scf_atoms.json", basis: str = "sto-3g", cart: bool = False):
    """Closed-shell atoms: a spherical atomic solver must reproduce these exactly."""
    out = []
    for symbol in ("He", "Be", "Ne", "Mg", "Ar"):
        mol = make_mol([(symbol, (0.0, 0.0, 0.0))], "Angstrom", basis, cart, 0)
        mf = dft.RKS(mol)
        mf.xc = "lda,vwn5"
        mf.grids.level = REFERENCE_GRID_LEVEL
        mf.conv_tol = 1e-11
        energy = float(mf.kernel())
        assert mf.converged
        out.append(
            {
                "symbol": symbol,
                "z": int(mol.atom_charge(0)),
                "n_electrons": int(mol.nelectron),
                "nbf": int(mol.nao),
                "energy": energy,
            }
        )
    dump(filename, {"functional": "lda,vwn5", "basis": basis, "atoms": out})


