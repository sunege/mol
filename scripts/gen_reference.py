#!/usr/bin/env python3
"""Generates the basis/grid tables and the reference values the Rust tests check against.

Nothing in `dft-core` may contain numbers typed from memory: every table and
every expected value either comes out of this script or is derived
independently inside the test itself.

Outputs:
  crates/dft-core/src/basis/sto3g_data.rs    STO-3G contractions for H-Ar
  crates/dft-core/src/grid/lebedev_data.rs   Lebedev-Laikov angular grids
  crates/dft-core/tests/data/*.json          reference integrals, XC values, energies

Usage:
  python3 -m venv .venv && .venv/bin/pip install pyscf
  .venv/bin/python scripts/gen_reference.py
"""

from __future__ import annotations

import json
import random
from pathlib import Path

import numpy as np
from pyscf import dft, gto
from pyscf.data.elements import ELEMENTS
from pyscf.dft import gen_grid

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "crates" / "dft-core" / "tests" / "data"

# Angular grid orders the engine embeds; the pruning scheme picks among these.
LEBEDEV_POINTS = [26, 50, 110, 194, 302]

# A dense grid makes the DFT reference energies essentially grid-converged, so a
# disagreement in the Rust tests points at the functional or the integrals
# rather than at quadrature noise.
REFERENCE_GRID_LEVEL = 9

SEED = 20260918


def f(x: float) -> str:
    """Round-trippable float literal."""
    return repr(float(x))


# --------------------------------------------------------------------------
# STO-3G table
# --------------------------------------------------------------------------


def write_sto3g() -> None:
    lines = [
        "//! STO-3G contraction data for H-Ar.",
        "//!",
        "//! GENERATED by `scripts/gen_reference.py` from the STO-3G definition",
        "//! shipped with PySCF (Hehre, Stewart and Pople, J. Chem. Phys. 51, 2657",
        "//! (1969) and its second/third-row extensions). Do not edit by hand.",
        "//!",
        "//! Coefficients multiply *normalised* primitive Gaussians, which is the",
        "//! convention of the published tables; `Shell` applies that normalisation",
        "//! and then renormalises the contracted function.",
        "",
        "use super::ShellDef;",
        "",
        "/// Shell definitions for each element, indexed by `z - 1`.",
        "pub static STO3G: [&[ShellDef]; 18] = [",
    ]
    for z in range(1, 19):
        symbol = ELEMENTS[z]
        shells = gto.basis.load("sto-3g", symbol)
        lines.append(f"    // {symbol}")
        lines.append("    &[")
        for shell in shells:
            l = shell[0]
            prims = shell[1:]
            exps = ", ".join(f(p[0]) for p in prims)
            coef = ", ".join(f(p[1]) for p in prims)
            lines.append(
                f"        ShellDef {{ l: {l}, exponents: &[{exps}], coefficients: &[{coef}] }},"
            )
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    out = ROOT / "crates" / "dft-core" / "src" / "basis" / "sto3g_data.rs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


# --------------------------------------------------------------------------
# Lebedev angular grids
# --------------------------------------------------------------------------


def write_lebedev() -> None:
    order_of = {n: deg for deg, n in gen_grid.LEBEDEV_ORDER.items()}
    lines = [
        "//! Lebedev-Laikov angular quadrature grids.",
        "//!",
        "//! GENERATED by `scripts/gen_reference.py` from the tables in PySCF/libcint",
        "//! (V. I. Lebedev and D. N. Laikov, Doklady Mathematics 59, 477 (1999)).",
        "//! Do not edit by hand.",
        "//!",
        "//! Points are unit vectors and weights sum to one, so a spherical average",
        "//! is `sum(w_i f(r_i))` and a surface integral is `4 pi` times that.",
        "",
        "/// One angular grid: unit vectors with weights summing to one.",
        "pub struct LebedevGrid {",
        "    /// Highest spherical-harmonic degree the grid integrates exactly.",
        "    pub degree: u32,",
        "    pub points: &'static [[f64; 3]],",
        "    pub weights: &'static [f64],",
        "}",
        "",
        "/// Available grids, ordered from coarsest to finest.",
        f"pub static GRIDS: [LebedevGrid; {len(LEBEDEV_POINTS)}] = [",
    ]
    for n in LEBEDEV_POINTS:
        grid = gen_grid.MakeAngularGrid(n)
        assert grid.shape == (n, 4), grid.shape
        assert abs(grid[:, 3].sum() - 1.0) < 1e-14
        pts = ",\n".join(
            f"            [{f(p[0])}, {f(p[1])}, {f(p[2])}]" for p in grid
        )
        wts = ",\n".join(f"            {f(w)}" for w in grid[:, 3])
        lines += [
            "    LebedevGrid {",
            f"        degree: {order_of[n]},",
            "        points: &[",
            pts + ",",
            "        ],",
            "        weights: &[",
            wts + ",",
            "        ],",
            "    },",
        ]
    lines += ["];", ""]
    out = ROOT / "crates" / "dft-core" / "src" / "grid" / "lebedev_data.rs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)} ({sum(LEBEDEV_POINTS)} points)")


