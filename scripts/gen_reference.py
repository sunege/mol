# Open-shell (unrestricted) references
# --------------------------------------------------------------------------

# Spin multiplicity of each open-shell reference, 2S+1. O2 carries the whole
# point of the automatic search: its ground state is the triplet, and nothing in
# the geometry says so.
OPEN_SHELL_MOLECULES = [
    ("o2_triplet", "o2", 3),
    ("o2_singlet", "o2", 1),
    ("ch3_doublet", "ch3", 2),
    ("oh_doublet", "oh", 2),
]

# Atoms, where the unrestricted solution differs most from the restricted one.
# Nitrogen is a quartet: three unpaired electrons exercise a multiplicity the
# molecular cases never reach. Aluminium and silicon are the hard ones - their
# 3s and 3p levels are close enough that an ordinary SCF oscillates between the
# equivalent ways of occupying the shell, and the engine needs a level shift to
# reach the answer PySCF reaches with its second-order solver.
OPEN_SHELL_ATOMS = [("H", 2), ("C", 3), ("N", 4), ("O", 3), ("Al", 2), ("Si", 3)]


def unrestricted_payload(mol, label: str) -> dict:
    """Converges one system with UKS (or RKS when it is closed-shell) and
    records everything a Rust test needs to localise a disagreement."""
    restricted = mol.spin == 0
    mf = dft.RKS(mol) if restricted else dft.UKS(mol)
    mf.xc = "lda,vwn5"
    mf.grids.level = REFERENCE_GRID_LEVEL
    mf.conv_tol = 1e-11
    energy = float(mf.kernel())
    if not mf.converged:
        # An open-shell atom has a partly filled, exactly degenerate p shell, and
        # ordinary DIIS oscillates between the equivalent ways of occupying it.
        # The second-order solver walks down to the stationary point instead of
        # rediagonalising, so the degeneracy costs it nothing.
        mf = mf.newton()
        energy = float(mf.kernel())
    assert mf.converged, f"{label} did not converge"

    dm = mf.make_rdm1()
    mo_energy = mf.mo_energy
    if restricted:
        # Written in the same shape as the open-shell case so the Rust side has
        # one code path: a closed shell is the special case where the two spin
        # channels are identical.
        dm = np.array([dm * 0.5, dm * 0.5])
        mo_energy = np.array([mo_energy, mo_energy])

    n_alpha, n_beta = mol.nelec
    payload = {
        "key": label,
        "charge": int(mol.charge),
        "multiplicity": int(mol.spin) + 1,
        "n_alpha": int(n_alpha),
        "n_beta": int(n_beta),
        "unrestricted": not restricted,
        "atoms": [
            {
                "z": int(mol.atom_charge(i)),
                "pos": [float(x) for x in mol.atom_coord(i)],
            }
            for i in range(mol.natm)
        ],
        "nbf": int(mol.nao),
        "n_electrons": int(mol.nelectron),
        "nuclear_repulsion": float(mol.energy_nuc()),
        "energy": energy,
        "e_core": float(mf.scf_summary["e1"]),
        "e_coulomb": float(mf.scf_summary["coul"]),
        "e_xc": float(mf.scf_summary["exc"]),
        # Per spin channel, alpha first.
        "mo_energies": [[float(x) for x in row] for row in mo_energy],
        "density_matrix": [flat(block) for block in dm],
        # <S^2>, which says how far the unrestricted solution is from a spin
        # eigenstate. The engine computes it the same way and must agree.
        "spin_squared": float(mf.spin_square()[0]) if not restricted else 0.0,
    }
    coarse = dft.RKS(mol) if restricted else dft.UKS(mol)
    coarse.xc = "lda,vwn5"
    coarse.grids.level = 3
    coarse.conv_tol = 1e-11
    payload["energy_grid_level_3"] = float(coarse.kernel())
    return payload


def open_shell_reference() -> None:
    systems = []
    for key, name, multiplicity in OPEN_SHELL_MOLECULES:
        mol = build_mol(name, spin=multiplicity - 1)
        systems.append(unrestricted_payload(mol, key))

    atoms = []
    for symbol, multiplicity in OPEN_SHELL_ATOMS:
        mol = gto.Mole()
        mol.atom = [(symbol, (0.0, 0.0, 0.0))]
        mol.basis = "sto-3g"
        mol.spin = multiplicity - 1
        mol.verbose = 0
        mol.build()
        atoms.append(unrestricted_payload(mol, f"{symbol.lower()}_atom"))

    dump(
        "scf_open_shell.json",
        {
            "functional": "lda,vwn5",
            "basis": "sto-3g",
            "grid_level": REFERENCE_GRID_LEVEL,
            "systems": systems,
            "atoms": atoms,
        },
    )


# --------------------------------------------------------------------------
# Analytic nuclear gradients, and a relaxed geometry to compare against
# --------------------------------------------------------------------------

# Geometries the Rust gradient tests check, with the spin multiplicity each is
# solved at. The distorted ones carry large forces, which is the point: a term
# that is wrong by a few percent shows up as a few percent of something big.
GRADIENT_CASES = [
    ("h2o_distorted", "h2o_distorted", 1),
    ("ch4_distorted", "ch4_distorted", 1),
    ("o2_stretched_triplet", "o2_stretched", 3),
    ("ch3_doublet", "ch3", 2),
]


def _mean_field(mol):
    """A converged SVWN5 calculation, restricted or not as the spin requires."""
    mf = dft.RKS(mol) if mol.spin == 0 else dft.UKS(mol)
    mf.xc = "lda,vwn5"
    mf.grids.level = REFERENCE_GRID_LEVEL
    mf.conv_tol = 1e-12
    energy = float(mf.kernel())
    if not mf.converged:
        mf = mf.newton()
        energy = float(mf.kernel())
    assert mf.converged
    return mf, energy


def _analytic_gradient(mf):
    """dE/dR in Hartree/Bohr, with the grid held still.

    `grid_response = False` is PySCF's default and is the same approximation the
    engine makes: the derivatives of the Becke weights are left out. Turning it
    on here would compare two different quantities.
    """
    grad = mf.nuc_grad_method()
    grad.grid_response = False
    return grad.kernel()


def gradient_reference(
    filename: str, basis: str, cart: bool, relaxed: list[tuple[str, int]]
) -> None:
    cases = []
    for key, name, multiplicity in GRADIENT_CASES:
        mol = build_mol(name, basis=basis, cart=cart, spin=multiplicity - 1)
        mf, energy = _mean_field(mol)
        gradient = _analytic_gradient(mf)
        cases.append(
            {
                "key": key,
                "multiplicity": multiplicity,
                "atoms": [
                    {
                        "z": int(mol.atom_charge(i)),
                        "pos": [float(x) for x in mol.atom_coord(i)],
                    }
                    for i in range(mol.natm)
                ],
                "energy": energy,
                # Hartree/Bohr, [natm][3].
                "gradient": [[float(x) for x in row] for row in gradient],
            }
        )

    dump(
        filename,
        {
            "functional": "lda,vwn5",
            "basis": basis,
            "grid_level": REFERENCE_GRID_LEVEL,
            "grid_response": False,
            "source": "pyscf mf.nuc_grad_method().kernel()",
            "cases": cases,
            "relaxed": [
                relaxed_geometry(name, multiplicity, basis, cart)
                for name, multiplicity in relaxed
            ],
        },
    )


def relaxed_geometry(name: str, multiplicity: int, basis: str, cart: bool) -> dict:
    """Minimises the energy with scipy's BFGS over PySCF energies and gradients.

    Deliberately not PySCF's own geometry optimiser: an independent optimiser
    over an independent engine is the better reference - if the Rust optimiser
    lands on the same structure, two different minimisers agreed about where the
    minimum is.
    """
    from scipy.optimize import minimize

    template = GEOMETRIES[name]
    symbols = [symbol for symbol, _ in template]

    def build(flat_bohr):
        atoms = [
            (symbol, tuple(flat_bohr[3 * i : 3 * i + 3]))
            for i, symbol in enumerate(symbols)
        ]
        return make_mol(atoms, "Bohr", basis, cart, multiplicity - 1)

    def objective(flat_bohr):
        mf, energy = _mean_field(build(flat_bohr))
        return energy, _analytic_gradient(mf).ravel()

    start = build_mol(name, spin=multiplicity - 1).atom_coords().ravel()
    outcome = minimize(objective, start, jac=True, method="BFGS", tol=1e-8,
                       options={"gtol": 1e-6, "maxiter": 200})
    assert outcome.success, f"{name} did not relax: {outcome.message}"

    coords = np.asarray(outcome.x).reshape(-1, 3)

    def distance(i, j):
        return float(np.linalg.norm(coords[i] - coords[j]))

    def angle(i, j, k):
        u = coords[i] - coords[j]
        v = coords[k] - coords[j]
        cosine = float(u @ v / (np.linalg.norm(u) * np.linalg.norm(v)))
        return float(np.degrees(np.arccos(np.clip(cosine, -1.0, 1.0))))

    # Every bond from the first atom, which is the heavy one in both cases here,
    # plus one angle across it. Enough to pin the structure without writing out
    # coordinates that depend on an arbitrary orientation.
    bonds = [distance(0, i) for i in range(1, len(symbols))]
    return {
        "key": name,
        "multiplicity": multiplicity,
        "symbols": symbols,
        "start": [float(x) for x in start],
        "energy": float(outcome.fun),
        "max_force": float(np.abs(outcome.jac).max()),
        # Bohr.
        "coords": [float(x) for x in np.asarray(outcome.x)],
        "bonds_from_first_atom": bonds,
        "angle_1_0_2": angle(1, 0, 2),
    }


def flat(matrix) -> list[float]:
    return [float(x) for x in np.asarray(matrix).ravel()]


def dump(filename: str, payload: dict) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    path = DATA / filename
    path.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size / 1024:.0f} kB)")


def main() -> None:
    write_units()
    write_sto3g()
    write_631gs()
    write_lebedev()
    write_xc()

    integral_reference("h2_sto3g", "h2", "sto-3g", cart=False, full_eri=True)
    integral_reference("h2o_sto3g", "h2o_distorted", "sto-3g", cart=False, full_eri=True)
    integral_reference("h2s_sto3g", "h2s", "sto-3g", cart=False, full_eri=False)
    integral_reference("co2_sto3g", "co2", "sto-3g", cart=False, full_eri=False)
    # The integral tests check the l = 2 path against this one, and
    # `b631gs_table_matches_reference` checks the engine's 6-31G* table against
    # the shells PySCF used for it.
    integral_reference("h2o_631gs", "h2o_distorted", "6-31G*", cart=True, full_eri=False)

    for key, name in [
        ("h2", "h2"),
        ("h2o", "h2o"),
        ("ch4", "ch4"),
        ("nh3", "nh3"),
        ("h2s", "h2s"),
        ("co2", "co2"),
    ]:
        scf_reference(key, name)
    scf_reference("benzene", "benzene", with_density=False)
    atomic_reference()
    open_shell_reference()
    gradient_reference("gradients.json", "sto-3g", False, [("h2o", 1), ("ch4", 1)])

    # 6-31G*, the basis of the "measure the shape" level. Benzene is left out:
    # one 6-31G* SCF of it takes the engine about 10 s and the tests solve each
    # file several times, while water, methane and ammonia already put the d
    # shell on three different first-row atoms (the atoms add Mg and Ar).
    for name in ("h2o", "ch4", "nh3"):
        scf_reference(f"{name}_631gs", name, basis="6-31G*", cart=True)
    atomic_reference("scf_atoms_631gs.json", "6-31G*", cart=True)
    gradient_reference("gradients_631gs.json", "6-31G*", True, [("h2o", 1)])


if __name__ == "__main__":
    main()
