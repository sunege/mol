def write_basis_table(pyscf_name: str, static: str, header: list[str], filename: str) -> None:
    """One `[&[ShellDef]; 18]` table for H-Ar, shells in PySCF's order.

    Every row PySCF loads is `[exponent, coefficient]`: neither table here is
    generally contracted (an SP shell arrives already split into s and p), so a
    shell is exactly one `ShellDef`. A generally contracted basis would need a
    loop over coefficient columns, and the assert says so rather than silently
    keeping the first.
    """
    lines = header + [
        "",
        "use super::ShellDef;",
        "",
        "/// Shell definitions for each element, indexed by `z - 1`.",
        f"pub static {static}: [&[ShellDef]; 18] = [",
    ]
    for z in range(1, 19):
        symbol = ELEMENTS[z]
        shells = gto.basis.load(pyscf_name, symbol)
        lines.append(f"    // {symbol}")
        lines.append("    &[")
        for shell in shells:
            l = shell[0]
            prims = shell[1:]
            assert all(len(p) == 2 for p in prims), f"{pyscf_name} {symbol}: general contraction"
            exps = ", ".join(f(p[0]) for p in prims)
            coef = ", ".join(f(p[1]) for p in prims)
            lines.append(
                f"        ShellDef {{ l: {l}, exponents: &[{exps}], coefficients: &[{coef}] }},"
            )
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    out = ROOT / "crates" / "dft-core" / "src" / "basis" / filename
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


