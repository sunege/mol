# Angular grid orders the engine embeds; the pruning scheme picks among these.
LEBEDEV_POINTS = [26, 50, 110, 194, 302]

# A dense grid makes the DFT reference energies essentially grid-converged, so a
# disagreement in the Rust tests points at the functional or the integrals
# rather than at quadrature noise.
REFERENCE_GRID_LEVEL = 9

SEED = 20260918


def f(x: float) -> str:
    """Round-trippable float literal."""
    return repr(float(x))


# --------------------------------------------------------------------------
# Units for the web side
# --------------------------------------------------------------------------


def write_units() -> None:
    """The conversion the structure log shows energies in.

    The interface never shows a total energy in Hartree next to another one:
    what a class compares is how much deeper one shape is than another, and that
    is a chemist's number, kJ/mol. The factor is one mole of Hartrees, and like
    every other constant here it is generated rather than typed.
    """
    hartree, unit, uncertainty = constants.physical_constants["Hartree energy"]
    payload = {
        "_comment": (
            "GENERATED by scripts/gen_reference.py. Do not edit by hand. "
            "One Hartree per particle, in kilojoules per mole."
        ),
        "source": (
            f"scipy.constants {scipy.__version__}: "
            "physical_constants['Hartree energy'] and Avogadro (CODATA)"
        ),
        "hartreeEnergy": {"value": hartree, "unit": unit, "uncertainty": uncertainty},
        "avogadro": constants.Avogadro,
        "hartreeToKilojoulesPerMole": hartree * constants.Avogadro / 1000.0,
    }
    path = WEB / "records" / "units.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


